import os
from typing import Tuple, List, Dict, Any
from dotenv import load_dotenv
from supabase import create_client, Client

load_dotenv()

def get_supabase_credentials() -> Tuple[str, str]:
    url = os.getenv("NEXT_PUBLIC_SUPABASE_URL") or os.getenv("SUPABASE_URL") or ""
    key = os.getenv("NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY") or os.getenv("SUPABASE_KEY") or ""
    return url.strip(), key.strip()

_CLIENT: Client | None = None
_MISSING_TABLE_WARNED = set()

def _handle_supabase_error(tag: str, exc: Exception):
    err_str = str(exc)
    if "PGRST205" in err_str or "Could not find the table" in err_str:
        table_name = "target table"
        if "'" in err_str:
            parts = err_str.split("'")
            if len(parts) >= 2:
                table_name = parts[1]
        
        if table_name not in _MISSING_TABLE_WARNED:
            _MISSING_TABLE_WARNED.add(table_name)
            print(f"[Supabase Notice]: Table '{table_name}' not found. Please execute the SQL Migration script in your Supabase SQL Editor to create tables.")
    else:
        print(f"[{tag}]: {exc}")

def get_supabase() -> Client | None:
    """Returns a Supabase client singleton if configured."""
    global _CLIENT
    if _CLIENT is not None:
        return _CLIENT

    url, key = get_supabase_credentials()
    if not url or not key:
        return None

    try:
        _CLIENT = create_client(url, key)
        return _CLIENT
    except Exception as e:
        print(f"[Supabase Init Error]: {e}")
        return None

def test_connection() -> Tuple[bool, str]:
    """Tests connection to Supabase instance."""
    url, key = get_supabase_credentials()
    if not url or not key:
        return False, "Missing Supabase URL or Key in environment variables."

    client = get_supabase()
    if not client:
        return False, "Failed to initialize Supabase client."

    try:
        return True, f"Connected to Supabase project at {url}"
    except Exception as e:
        return False, f"Supabase connection test failed: {e}"

