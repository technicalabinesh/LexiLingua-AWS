def save_chat_message(session_id: str, role: str, content: str, model: str = "openai/gpt-oss-120b") -> bool:
    client = get_supabase()
    if not client:
        return False
    try:
        client.table("chat_history").insert({
            "session_id": session_id,
            "role": role,
            "content": content,
            "model": model,
        }).execute()
        return True
    except Exception as e:
        _handle_supabase_error("Supabase Save Chat Error", e)
        return False

def load_chat_history(session_id: str) -> List[Dict[str, Any]]:
    client = get_supabase()
    if not client:
        return []
    try:
        res = client.table("chat_history")\
            .select("role, content, model, created_at")\
            .eq("session_id", session_id)\
            .order("created_at", desc=False)\
            .execute()
        return res.data or []
    except Exception as e:
        _handle_supabase_error("Supabase Load Chat Error", e)
        return []

def save_summary_to_db(doc_data: dict) -> bool:
    client = get_supabase()
    if not client:
        return False
    try:
        client.table("document_summaries").insert({
            "filename": doc_data.get("filename", "Untitled.txt"),
            "summary": doc_data.get("summary", ""),
            "key_points": doc_data.get("key_points", []),
            "original_words": doc_data.get("original_words", 0),
            "summary_words": doc_data.get("summary_words", 0),
            "model": doc_data.get("model", "openai/gpt-oss-120b"),
        }).execute()
        return True
    except Exception as e:
        _handle_supabase_error("Supabase Save Summary Error", e)
        return False

def load_summaries_from_db(limit: int = 20) -> List[Dict[str, Any]]:
    client = get_supabase()
    if not client:
        return []
    try:
        res = client.table("document_summaries")\
            .select("*")\
            .order("created_at", desc=True)\
            .limit(limit)\
            .execute()
        return res.data or []
    except Exception as e:
        _handle_supabase_error("Supabase Load Summaries Error", e)
        return []

